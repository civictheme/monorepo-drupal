#!/usr/bin/env bash
# Salsa scaffold — what `COPY src/` actually delivers into the image.
#
# `.dockerignore` is a list of intentions. This is the result. It exports the
# exact file set the build context would hand to `COPY src/ /opt/drupal/` and
# diffs its shape against .docker/image-manifest.txt.
#
# It catches BOTH directions, which is the point — a denylist fails by shipping
# something extra, an allowlist by omitting something, and neither failure is
# visible from reading the list:
#
#   ADDED    a Composer or npm tree leaked past the exclusions; a developer's
#            local override, dump or credential file reached the context
#   REMOVED  a directory the project needs stopped shipping. This one is
#            invisible in local dev — docker-compose.override.yml bind-mounts
#            ./src over /opt/drupal, so the site works on your machine and
#            fails only once deployed.
#
# Runs a throwaway `FROM scratch` build so Docker's own .dockerignore engine
# decides what is in the context — no reimplementation of its matching rules,
# no base image pulled, nothing installed. Takes about a second.
#
# Usage:
#   ahoy image-manifest             # check; non-zero on any difference
#   ahoy image-manifest --update    # adopt the current shape (review the diff!)
#
# Depth is directories to $DEPTH plus files at the top level, so the manifest
# records structure rather than every file — adding a module does not churn it,
# but adding web/modules/contrib does.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="${ROOT:-$(cd "$HERE/../.." && pwd)}"
MANIFEST="${MANIFEST:-$ROOT/.docker/image-manifest.txt}"
DEPTH="${DEPTH:-3}"

log()  { printf '\033[0;36m[image-manifest]\033[0m %s\n' "$*"; }
die()  { printf '\033[0;31m[image-manifest]\033[0m %s\n' "$*" >&2; exit 2; }

update=0
case "${1:-}" in
  --update)  update=1 ;;
  -h|--help) sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
  '')        ;;
  *)         die "Unknown argument '$1'. Try --update or --help." ;;
esac

command -v docker >/dev/null 2>&1 || die "docker not found — see \`ahoy doctor\`."

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT HUP INT TERM

# BuildKit's --output. Docker has shipped it by default since 23.0; on an older
# daemon the failure is an unhelpful "unknown flag", so set it rather than
# explain it. Same reasoning as `ahoy fe-build`.
export DOCKER_BUILDKIT=1

# The Dockerfile comes from stdin so nothing has to be added to the shipped one.
# The context is the repo root, exactly as docker-compose.yml declares it, so
# .dockerignore is read from the same place a real build reads it.
printf 'FROM scratch\nCOPY src/ /\n' \
  | docker build -q -f - --output "type=local,dest=$tmp/ctx" "$ROOT" >/dev/null \
  || die "context export failed — is the Docker daemon running?"

# Directories to $DEPTH, plus top-level files. LC_ALL=C so the ordering does not
# depend on the developer's locale.
{
  find "$tmp/ctx" -mindepth 1 -maxdepth "$DEPTH" -type d
  find "$tmp/ctx" -mindepth 1 -maxdepth 1 -type f
} | sed "s|^$tmp/ctx/||" | LC_ALL=C sort > "$tmp/current"

if [ "$update" -eq 1 ]; then
  mkdir -p "$(dirname "$MANIFEST")"
  {
    echo "# What \`COPY src/ /opt/drupal/\` delivers into the image."
    echo "# Generated by scripts/quant/image-manifest.sh --update — review diffs,"
    echo "# do not hand-edit. Directories to depth ${DEPTH}, plus top-level files."
    cat "$tmp/current"
  } > "$MANIFEST"
  log "Wrote ${MANIFEST#"$ROOT"/} ($(grep -cv '^#' "$MANIFEST") entries)"
  exit 0
fi

if [ ! -f "$MANIFEST" ]; then
  die "No ${MANIFEST#"$ROOT"/} yet. Create it with: ahoy image-manifest --update"
fi

grep -v '^#' "$MANIFEST" | LC_ALL=C sort > "$tmp/expected"

if diff -q "$tmp/expected" "$tmp/current" >/dev/null; then
  log "OK — image contents match ${MANIFEST#"$ROOT"/} ($(wc -l < "$tmp/current" | tr -d ' ') entries)."
  exit 0
fi

printf '\033[0;31m[image-manifest]\033[0m image contents differ from %s\n\n' \
  "${MANIFEST#"$ROOT"/}" >&2
LC_ALL=C comm -13 "$tmp/expected" "$tmp/current" | sed 's/^/  + ADDED    /' >&2
LC_ALL=C comm -23 "$tmp/expected" "$tmp/current" | sed 's/^/  - REMOVED  /' >&2
cat >&2 <<'EOF'

  ADDED    — check it belongs in a production image. If not, exclude it in
             .dockerignore. Composer- and npm-managed trees never belong.
  REMOVED  — check the project still works without it. A directory that
             vanished here still works locally (./src is bind-mounted) and
             fails only after deploy.

  Once the difference is intended:  ahoy image-manifest --update
EOF
exit 1
